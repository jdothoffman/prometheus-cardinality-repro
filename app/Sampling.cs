// Trace sampling for the api role: head sampling in the SDK, configurable, with a HARD CEILING of 75%.
//
// Where the ratio comes from (all of them are capped at MaxRatio):
//   TRACE_SAMPLE_RATIO   at startup. A value above the cap is clamped to it, with a warning in the log.
//   POST /admin/sampling?ratio=…   on a replica, live. Above the cap: 400, nothing changes.
//   the console's "Trace sampling" control → driver POST /api/sampling → every replica (and re-applied to
//                        replicas that restart with the env default).
// TRACING_ENABLED (default: TRACE_SAMPLE_RATIO > 0) decides at startup whether the tracing pipeline exists at
// all. Off means no TracerProvider and no per-request activity: the setting of every experiment run before
// tracing. While it's on, the ratio can be anything from 0 to the cap at runtime.
//
// The decision, per new span:
//   in-process child (local parent)   follow the parent: a trace is kept or dropped whole.
//   remote parent, not sampled        drop: an upstream "no" never raises the rate.
//   remote parent, sampled            OUR ratio decides, by a random draw. A plain ParentBased sampler would
//                                     trust the caller's sampled flag: any client sending `traceparent: …-01`
//                                     would get 100% of its requests traced, past the cap. A trace-id ratio
//                                     wouldn't hold either: here the CALLER picks the trace id, and the SDK's
//                                     TraceIdRatioBasedSampler keeps every id whose first 8 bytes are small
//                                     (00000000…), at any ratio above 0. The cost: an upstream-sampled trace
//                                     can lack this service's spans when our draw says no.
//   no parent (root)                  our ratio decides, with the SDK's TraceIdRatioBasedSampler: the trace id
//                                     was just generated by this SDK (random), so that's the same as a draw.
// Both caps hold for the expected share of traced requests; over a short window the observed share scatters
// around the ratio (about ±1.5 points at 1,000 requests and 75%). The ratio is swapped atomically on change.

using System.Diagnostics;
using OpenTelemetry.Trace;

sealed class TraceSampling
{
    public const double MaxRatio = 0.75;

    private volatile Sampler _byTraceId;
    private double _ratio;

    public TraceSampling(bool enabled, double requestedRatio, out string? startupWarning)
    {
        Enabled = enabled;
        startupWarning = null;
        var r = double.IsFinite(requestedRatio) ? Math.Max(0, requestedRatio) : 0;
        if (r > MaxRatio)
        {
            startupWarning = $"TRACE_SAMPLE_RATIO={requestedRatio} is above the {MaxRatio * 100:0}% cap; using {MaxRatio}";
            r = MaxRatio;
        }
        _ratio = enabled ? r : 0;
        _byTraceId = new TraceIdRatioBasedSampler(_ratio);
    }

    /// <summary>Whether the tracing pipeline was built at startup (TRACING_ENABLED).</summary>
    public bool Enabled { get; }

    public double Ratio => Volatile.Read(ref _ratio);

    internal Sampler ByTraceId => _byTraceId;

    /// <summary>Changes the ratio live. Rejects (does not clamp) values outside [0, MaxRatio].</summary>
    public bool TrySet(double ratio, out string? error)
    {
        if (!Enabled)
        {
            error = "tracing is off on this replica (started with TRACING_ENABLED=false): `make traces-on` first";
            return false;
        }
        if (!double.IsFinite(ratio) || ratio < 0 || ratio > MaxRatio)
        {
            error = $"ratio must be between 0 and {MaxRatio} (trace sampling is capped at {MaxRatio * 100:0}%); got {ratio}";
            return false;
        }
        _byTraceId = new TraceIdRatioBasedSampler(ratio); // one reference swap: each decision sees old or new, never a mix
        Volatile.Write(ref _ratio, ratio);
        error = null;
        return true;
    }

    public object Describe() => new { enabled = Enabled, ratio = Ratio, max = MaxRatio };
}

sealed class CappedRatioSampler(TraceSampling sampling) : Sampler
{
    private static readonly SamplingResult Keep = new(SamplingDecision.RecordAndSample);
    private static readonly SamplingResult Drop = new(SamplingDecision.Drop);

    public override SamplingResult ShouldSample(in SamplingParameters p)
    {
        var parent = p.ParentContext;
        if (parent.TraceId != default)
        {
            var parentSampled = (parent.TraceFlags & ActivityTraceFlags.Recorded) != 0;
            if (!parent.IsRemote || !parentSampled) return parentSampled ? Keep : Drop;
            // Caller-supplied trace id: don't let it pick the outcome.
            return Random.Shared.NextDouble() < sampling.Ratio ? Keep : Drop;
        }
        return sampling.ByTraceId.ShouldSample(p);
    }
}
